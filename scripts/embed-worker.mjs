// Packs dist/ into dist-worker/files.js so the Worker can serve the app without a separate assets upload.
import { readdirSync, readFileSync, statSync, mkdirSync, writeFileSync } from "node:fs"
import { join, relative, extname } from "node:path"

const root = "dist"
const types = {
  ".html": "text/html; charset=utf-8", ".js": "text/javascript; charset=utf-8",
  ".css": "text/css; charset=utf-8", ".svg": "image/svg+xml", ".png": "image/png",
  ".webmanifest": "application/manifest+json", ".json": "application/json",
}
const files = {}
const walk = (d) => readdirSync(d).forEach((f) => {
  const p = join(d, f)
  if (statSync(p).isDirectory()) return walk(p)
  const ext = extname(p)
  if (!types[ext]) throw new Error(`No content type for ${p}`)
  const binary = !types[ext].startsWith("text/") && !types[ext].includes("json") && ext !== ".svg"
  const data = readFileSync(p)
  files["/" + relative(root, p).replaceAll("\\", "/")] = [types[ext], binary ? data.toString("base64") : data.toString("utf8"), binary]
})
walk(root)

// The Worker (worker/index.ts) imports this module and serves the files from memory.
const code = `/** Generated by scripts/embed-worker.mjs from dist/. Do not edit. */
export const FILES = ${JSON.stringify(files)};
`
mkdirSync("dist-worker", { recursive: true })
writeFileSync("dist-worker/files.js", code)
writeFileSync("dist-worker/files.d.ts", "export declare const FILES: Record<string, [string, string, boolean]>\n")
console.log(`Embedded ${Object.keys(files).length} files, ${(code.length / 1024).toFixed(0)} KB`)
